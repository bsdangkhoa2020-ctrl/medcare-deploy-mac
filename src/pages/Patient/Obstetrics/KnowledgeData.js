export const getBabyDataForWeek = (week) => {
  // If exact week not found, find the closest previous week
  if (BABY_WEEKS_DATA[week]) return BABY_WEEKS_DATA[week];
  
  const weeks = Object.keys(BABY_WEEKS_DATA).map(Number).sort((a, b) => a - b);
  let closest = weeks[0];
  for (const w of weeks) {
    if (w <= week) closest = w;
    else break;
  }
  return BABY_WEEKS_DATA[closest];
};
